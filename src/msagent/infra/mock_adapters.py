@dataclass(slots=True)
class MockLLMAdapter(LLMAdapter):
    """稳定、可测试的 mock LLM adapter。"""

    evaluation_verdict_sequence: tuple[EvaluationVerdict, ...] = (
        EvaluationVerdict.ACCEPT,
    )
    evaluation_counter: int = 0

    def run_query_understanding(
        self, request: QueryUnderstandingAdapterRequest
    ) -> QueryUnderstandingResult:
        normalized_query = request.raw_query.strip()
        return QueryUnderstandingResult(
            understanding_id=f"{request.task_id}-understanding",
            normalized_query=normalized_query,
            target_summary=f"Target inferred from query: {normalized_query}",
            target_type=TargetType.OBJECT,
            implicitness=ImplicitnessLevel.EXPLICIT,
            canonical_referent_text=normalized_query,
            referent_number=ReferentNumber.SINGLE,
            focus_terms=[normalized_query],
            attribute_clues=[normalized_query],
            relation_clues=[
                RelationCue(
                    relation_type="self",
                    anchor_text=normalized_query,
                    cue_text="mock relation cue",
                )
            ],
            spatial_clues=[SpatialCue(cue_type="center_bias", cue_text="mock center prior")],
            route_hints=[
                RouteHint(
                    hint_type="prefer_locate",
                    reason="mock adapter defaults to locate route",
                    confidence=1.0,
                )
            ],
            bridge_hints=[
                QueryBridgeHint(
                    hint_type="preserve_raw_query",
                    reason="keep the original text for prompt bridge debugging",
                )
            ],
            confidence=0.95,
            notes=["generated by MockLLMAdapter"],
        )

    def run_evaluation(self, request: EvaluationAdapterRequest) -> EvaluationResult:
        verdict = self.evaluation_verdict_sequence[
            min(self.evaluation_counter, len(self.evaluation_verdict_sequence) - 1)
        ]
        self.evaluation_counter += 1

        primary_candidate = next(
            (
                candidate
                for candidate in request.segmentation.candidates
                if candidate.candidate_id == request.segmentation.primary_candidate_id
            ),
            request.segmentation.candidates[0] if request.segmentation.candidates else None,
        )

        if verdict is EvaluationVerdict.ACCEPT and primary_candidate is not None:
            return EvaluationResult(
                evaluation_id=f"{request.task_id}-evaluation-{self.evaluation_counter}",
                verdict=EvaluationVerdict.ACCEPT,
                summary=(
                    "Mock evaluator accepted the primary segmentation candidate "
                    f"for prompt '{request.prompt_package.text_prompts.normalized_text}'."
                ),
                accepted_candidate_id=primary_candidate.candidate_id,
                accepted_mask_ref=primary_candidate.mask_ref,
                confidence=0.98,
            )

        return EvaluationResult(
            evaluation_id=f"{request.task_id}-evaluation-{self.evaluation_counter}",
            verdict=verdict,
            summary="Mock evaluator rejected the segmentation candidate.",
            failure_type=FailureType.LOCALIZATION_ERROR,
            confidence=0.66,
            issues=[
                EvaluationIssue(
                    issue_type="mock_reject",
                    summary="Configured mock verdict rejected the current candidate.",
                    severity="medium",
                )
            ],
            retry_hints=["retry_with_same_route"],
        )


@dataclass(slots=True)
class MockLocatorAdapter(LocatorAdapter):
    """稳定的 locate proposal mock。"""

    def locate(self, request: LocateAdapterRequest) -> ProposalResult:
        candidate = ProposalCandidate(
            candidate_id="locate-candidate-1",
            rank=1,
            confidence=0.91,
            matched_clues=[
                request.understanding.normalized_query,
                *request.understanding.focus_terms,
            ],
            region_box=NormalizedBox(x1=0.2, y1=0.18, x2=0.72, y2=0.84),
            positive_point_hints=[
                PointHint(x=0.42, y=0.45, confidence=0.95, reason="target center"),
                PointHint(x=0.55, y=0.62, confidence=0.87, reason="target support"),
            ],
            negative_point_hints=[
                PointHint(x=0.1, y=0.12, confidence=0.72, reason="background corner"),
                PointHint(x=0.86, y=0.22, confidence=0.7, reason="distractor region"),
            ],
            rationale="Mock locate route returns one stable spatial prior.",
            limitations=["single_candidate_only"],
        )
        return ProposalResult(
            proposal_id=f"{request.task_id}-proposal-locate",
            route=ProposalRoute.LOCATE,
            status=ProposalStatus.READY,
            proposal_summary="Mock locator produced a single ready candidate.",
            candidates=[candidate],
            primary_candidate_id=candidate.candidate_id,
            matched_text_clues=[request.understanding.normalized_query],
            bridge_hints=[
                ProposalBridgeHint(
                    hint_type="prefer_box_plus_points",
                    reason="mock locate route provides box and point priors",
                ),
                ProposalBridgeHint(
                    hint_type="need_negative_points",
                    reason="mock candidate includes distractor suppression points",
                ),
            ],
            diagnostics=["generated by MockLocatorAdapter"],
        )


@dataclass(slots=True)
class MockSAMAdapter(SAMAdapter):
    """稳定的 mock segmenter backend。"""

    artifact_store: ArtifactStore = field(kw_only=True)
    mask_width: int = 10
    mask_height: int = 10
    default_box: NormalizedBox = field(
        default_factory=lambda: NormalizedBox(x1=0.25, y1=0.25, x2=0.75, y2=0.75)
    )

    def segment(self, request: SegmentAdapterRequest) -> SegmentationResult:
        resolved_box = self._resolve_active_box(request)
        mask_payload = MockMask(
            mask_id=f"{request.task_id}-mask-1",
            width=self.mask_width,
            height=self.mask_height,
            active_box=resolved_box,
            active_points=[
                (
                    int(point.x * self.mask_width),
                    int(point.y * self.mask_height),
                )
                for point in request.prompt_package.spatial_prompts.positive_points
            ],
        )
        mask_ref = self.artifact_store.save_artifact(ArtifactKind.MASK, mask_payload)
        candidate = SegmentationCandidate(
            candidate_id="segmentation-candidate-1",
            mask_ref=mask_ref,
            score=0.94,
            prompt_summary=request.prompt_package.text_prompts.normalized_text,
            notes=["generated by MockSAMAdapter"],
        )
        return SegmentationResult(
            segmentation_id=f"{request.task_id}-segmentation",
            status=SegmentationStatus.READY,
            result_summary="Mock SAM adapter produced one segmentation candidate.",
            candidates=[candidate],
            primary_candidate_id=candidate.candidate_id,
            diagnostics=["mock segmentation completed"],
        )

    def _resolve_active_box(self, request: SegmentAdapterRequest) -> NormalizedBox:
        boxes = request.prompt_package.spatial_prompts.boxes
        if boxes:
            first_box = boxes[0]
            return NormalizedBox(
                x1=first_box.x1,
                y1=first_box.y1,
                x2=first_box.x2,
                y2=first_box.y2,
            )

        positive_points = request.prompt_package.spatial_prompts.positive_points
        if positive_points:
            xs = [point.x for point in positive_points]
            ys = [point.y for point in positive_points]
            margin = 0.08
            return NormalizedBox(
                x1=max(0.0, min(xs) - margin),
                y1=max(0.0, min(ys) - margin),
                x2=min(1.0, max(xs) + margin),
                y2=min(1.0, max(ys) + margin),
            )

        return self.default_box
